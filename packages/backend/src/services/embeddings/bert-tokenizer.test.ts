test('bert tokenizer matches the reference token ids', () => {
  const cfg = configFromTokenizerJson(JSON.parse(readFileSync(TOKENIZER_FILE, 'utf8')));
  for (const { text, ids } of CASES) {
    const actual = encode(text, cfg, 512).inputIds;
    assert.deepEqual(actual, ids, `token ids differ for: ${JSON.stringify(text.slice(0, 60))}`);
  }
});

test('a word longer than the 100-char limit becomes a single [UNK]', () => {
  const cfg = configFromTokenizerJson(JSON.parse(readFileSync(TOKENIZER_FILE, 'utf8')));
  const ids = encode('a'.repeat(101), cfg, 512).inputIds;
  assert.deepEqual(ids, [cfg.clsId, cfg.vocab.get('[UNK]'), cfg.sepId]);
});

test('over-long input is cut to maxLength, losing the trailing [SEP]', () => {
  const cfg = configFromTokenizerJson(JSON.parse(readFileSync(TOKENIZER_FILE, 'utf8')));
  const ids = encode('word '.repeat(600), cfg, 512).inputIds;
  assert.equal(ids.length, 512);
  assert.equal(ids[0], cfg.clsId);
  assert.notEqual(ids[511], cfg.sepId);
});
